def test_gaussian_nll_matches_standard_normal_and_is_finite():
    mean=torch.zeros(4,dtype=torch.float64,requires_grad=True)
    target=torch.tensor([0.,1.,-1.,2.],dtype=torch.float64)
    log_std=torch.zeros(4,dtype=torch.float64,requires_grad=True)
    loss=gaussian_nll(mean,target,log_std)
    assert torch.isfinite(loss)
    assert loss.item()==pytest.approx(.5*(1.5+np.log(2*np.pi)),rel=1e-12)
    loss.backward()
    assert torch.isfinite(mean.grad).all()
    assert torch.isfinite(log_std.grad).all()


def test_gaussian_nll_bounds_log_std_and_supports_masking_by_caller():
    mean=torch.zeros(3)
    target=torch.ones(3)
    logs=torch.tensor([-100.,0.,100.])
    values=gaussian_nll(mean,target,logs,reduction="none")
    bounded=gaussian_nll(mean,target,logs.clamp(-7,4),reduction="none")
    assert torch.allclose(values,bounded)
    with pytest.raises(ValueError,match="identical shapes"):
        gaussian_nll(mean,target,torch.zeros(2))


def test_calibration_metrics_perfectly_calibrated_controlled_sample():
    # Deterministic symmetric residuals with sigma=1; empirical coverage is
    # checked against the exact values generated by this fixed fixture.
    residual=np.linspace(-3,3,6001)
    result=gaussian_calibration_metrics(np.zeros_like(residual),residual,np.ones_like(residual))
    assert result["status"]=="PASS"
    assert result["count"]==6001
    assert result["coverage"]["0.95"]==pytest.approx(np.mean(np.abs(residual)<=1.959963984540054))
    assert result["gaussian_nll"]==pytest.approx(.5*(np.mean(residual**2)+np.log(2*np.pi)))
    assert result["mean_interval_width"]["0.95"]==pytest.approx(2*1.959963984540054)


def test_calibration_respects_mask_and_reports_geometry_group_macro_metrics():
    mu=np.zeros((6,2)); y=np.array([[0,0],[1,0],[0,1],[3,3],[4,4],[5,5]],float)
    sigma=np.ones_like(y); mask=np.array([1,1,1,1,0,0],bool)
    groups=np.array(["A","A","B","B","C","C"])
    report=gaussian_calibration_metrics(mu,y,sigma,mask=mask,group_ids=groups)
    assert report["count"]==4
    assert report["source_group_count"]==2
    assert {g["group_id"] for g in report["groups"]}=={"A","B"}
    assert "group_macro_coverage" in report


def test_calibration_rejects_invalid_uncertainty_or_empty_mask():
    with pytest.raises(ValueError,match="strictly positive"):
        gaussian_calibration_metrics([0,0],[1,1],[1,0])
    with pytest.raises(ValueError,match="selects no samples"):
        gaussian_calibration_metrics([0,0],[1,1],[1,1],mask=[False,False])
    with pytest.raises(ValueError,match="nominal_levels"):
        gaussian_calibration_metrics([0],[1],[1],nominal_levels=(1.0,))


